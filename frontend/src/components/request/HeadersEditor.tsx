'use client';

import { Info } from 'lucide-react';
import { useRequestStore } from '@/store/requestStore';
import { KeyValueEditor } from './KeyValueEditor';

const COMMON_HEADER_KEYS = [
  'Authorization',
  'Content-Type',
  'Accept',
  'User-Agent',
  'Cache-Control',
  'Origin',
  'Referer',
  'Cookie',
  'X-API-Key',
  'Accept-Language',
  'Connection',
  'Pragma',
];

const COMMON_HEADER_VALUES = [
  'application/json',
  'application/x-www-form-urlencoded',
  'application/xml',
  'multipart/form-data',
  'text/plain',
  'Bearer {{token}}',
  'Basic {{credentials}}',
  'no-cache',
  'keep-alive',
  'utf-8',
  'gzip, deflate, br',
];

export function HeadersEditor() {
  const { getActiveTab, updateActiveTab } = useRequestStore();
  const activeTab = getActiveTab();

  if (!activeTab) return null;

  return (
    <div className="space-y-3">
      <KeyValueEditor
        idPrefix="request-header"
        rows={activeTab.headers || []}
        onChange={(headers) => updateActiveTab({ headers })}
        keyPlaceholder="Header name"
        valuePlaceholder="Header value"
        addLabel="Add header"
        emptyTitle="No custom headers"
        emptyDescription="Add headers such as Content-Type or Authorization. Headers generated by the auth tab are merged when you send."
        keySuggestions={COMMON_HEADER_KEYS}
        valueSuggestions={COMMON_HEADER_VALUES}
      />

      <p className="flex items-start gap-2 rounded-lg border border-border bg-surface-2/35 px-3 py-2 text-2xs leading-relaxed text-muted-foreground">
        <Info className="mt-0.5 h-3.5 w-3.5 shrink-0" aria-hidden />
        <span>
          Custom headers override generated auth headers with the same name. Use{' '}
          <code className="font-mono text-foreground">{'{{variable}}'}</code> to reference the active
          environment.
        </span>
      </p>
    </div>
  );
}
